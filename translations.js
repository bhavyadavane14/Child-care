// Helper to get translated string
function t(key, fallback = '') {
  // Dynamic clinical content (IAP schedule, milestones, symptoms, articles)
  if (currentLang !== 'en' && DATA_I18N[currentLang] && DATA_I18N[currentLang][key]) {
    return DATA_I18N[currentLang][key];
  }
  if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) {
    return TRANSLATIONS[currentLang][key];
  }
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return fallback || key;
}

// Helper to get translated string with {placeholder} interpolation
function tf(key, vars = {}, fallback = '') {
  let str = t(key, fallback);
  if (vars && typeof vars === 'object') {
    Object.keys(vars).forEach(name => {
      str = str.split('{' + name + '}').join(vars[name]);
    });
  }
  return str;
}

